use std::collections::BTreeMap;
use std::sync::Arc;

use crate::EffectSpec;
use crate::plugin::{EffectPlugin, PluginFrame, PluginManifest, PluginParams, register_plugin};

type Row = (&'static str, &'static str, &'static str, &'static str, &'static str, &'static str);

fn row(s: &EffectSpec) -> Row {
    let id = s.id;
    let plugin = !id.starts_with("ec.");
    let clock = crate::is_time_dependent(id);
    let frames = effectcraft_project::reads_other_frames(id);
    let history = id.starts_with("ec.time.") || crate::reads_param_history(id) || (plugin && crate::plugin::reads_other_times(id));
    let time = match (clock, frames, history) {
        (false, false, false) => "frame",
        (true, false, false) => "clock",
        (false, true, false) => "other-frames",
        (true, true, false) => "neighbours",
        (true, true, true) => "history",
        _ => "unrepresentable",
    };
    (
        s.id,
        if crate::audio_fx::is_audio_effect(id) { "audio" } else { "filter" },
        if s.gpu { "gpu" } else { "cpu" },
        time,
        if crate::READS_COMP_SCENE.contains(&id) { "comp-scene" } else { "layer" },
        if s.skips_cover() { "own-margins" } else { "layer" },
    )
}

fn mismatches(got: impl IntoIterator<Item = Row>, want: &[Row]) -> Vec<String> {
    let got: BTreeMap<&str, Row> = got.into_iter().map(|r| (r.0, r)).collect();
    let want: BTreeMap<&str, Row> = want.iter().map(|r| (r.0, *r)).collect();
    let ids: std::collections::BTreeSet<&str> = got.keys().chain(want.keys()).copied().collect();
    ids.into_iter().filter(|id| got.get(id) != want.get(id)).map(|id| format!("{id}: declared {:?}, expected {:?}", got.get(id), want.get(id))).collect()
}

#[test]
fn every_registered_effect_declares_what_the_old_lists_said() {
    let wrong = mismatches(crate::registry().iter().map(row), BUILT_IN);
    assert_eq!(BUILT_IN.len(), 308);
    assert!(wrong.is_empty(), "{} effects differ:\n{}", wrong.len(), wrong.join("\n"));
}

struct TestPlugin {
    manifest: PluginManifest,
    reads_other_times: bool,
}

impl EffectPlugin for TestPlugin {
    fn manifest(&self) -> &PluginManifest {
        &self.manifest
    }

    fn render(&self, _frame: &mut PluginFrame, _params: &PluginParams, _time: f64) -> Result<(), String> {
        Ok(())
    }

    fn reads_other_times(&self) -> bool {
        self.reads_other_times
    }
}

fn plugin(id: &str, reads_other_times: bool) -> &'static EffectSpec {
    let manifest = PluginManifest {
        api: 2,
        id: id.into(),
        name: id.into(),
        category: "Utility".into(),
        version: String::new(),
        author: String::new(),
        description: String::new(),
        params: vec![],
    };
    register_plugin(Arc::new(TestPlugin { manifest, reads_other_times })).unwrap()
}

